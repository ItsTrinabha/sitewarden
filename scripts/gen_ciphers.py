def main() -> None:
    out = subprocess.run(
        ["openssl", "ciphers", "-V", "-stdname", "ALL:COMPLEMENTOFALL:@SECLEVEL=0"],
        capture_output=True, text=True, check=True,
    ).stdout
    table: dict[int, tuple[str, str]] = {}
    for line in out.splitlines():
        m = re.match(r"\s*0x([0-9A-F]{2}),0x([0-9A-F]{2}) - (\S+)\s+- (\S+)", line)
        if m:
            code = int(m.group(1) + m.group(2), 16)
            table[code] = (m.group(3), m.group(4))
    for line in LEGACY.strip().splitlines():
        code_s, name = line.split()
        table.setdefault(int(code_s, 16), (name, ""))
    lines = [
        '"""Generated by scripts/gen_ciphers.py. Do not edit by hand."""',
        "",
        "# code: (IANA name, OpenSSL name)",
        "CIPHERS: dict[int, tuple[str, str]] = {",
    ]
    for code in sorted(table):
        iana, ossl = table[code]
        lines.append(f"    0x{code:04X}: ({iana!r}, {ossl!r}),")
    lines.append("}")
    path = pathlib.Path(__file__).resolve().parents[1] / "sitewarden" / "tls" / "cipher_table.py"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(table)} suites to {path}")


if __name__ == "__main__":
    main()
