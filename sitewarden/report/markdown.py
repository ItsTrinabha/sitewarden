"""Markdown report, suitable for tickets, pull requests and GitHub job summaries."""

from __future__ import annotations

ICON = {"critical": "🟥", "high": "🔴", "medium": "🟠", "low": "🔵", "info": "⚪", "pass": "✅"}


def _esc(s: str) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ")


def render(report: dict, show_passed: bool = True) -> str:
    lines = [f"# Sitewarden report: {report['target']}", ""]
    lines.append(f"**Grade: {report['grade']}** (score {report['score']}/100) · scanned {report['scanned_at']}"
                 + (f" · IP {report['ip']}" if report.get("ip") else ""))
    if report.get("capped_by"):
        lines.append("")
        lines.append("> Grade capped by: " + "; ".join(report["capped_by"]))
    lines += ["", "| Category | Grade | Score |", "|---|---|---|"]
    for info in report.get("categories", {}).values():
        if info.get("skipped"):
            lines.append(f"| {info['label']} | – | skipped |")
        else:
            lines.append(f"| {info['label']} | {info['grade']} | {info['score']} |")
    findings = report.get("findings", [])
    issues = [f for f in findings if f["severity"] not in ("pass", "info")]
    lines += ["", f"## Issues ({len(issues)})", ""]
    if not issues:
        lines.append("No issues found.")
    for f in issues:
        lines.append(f"### {ICON[f['severity']]} {f['title']}")
        lines.append(f"*{f['severity'].upper()} · {f['category']}*" + (f" · `{'`, `'.join(f['tags'][:4])}`" if f.get("tags") else ""))
        lines.append("")
        if f.get("detail"):
            lines.append(f["detail"])
            lines.append("")
        if f.get("evidence"):
            lines.append(f"Evidence: `{f['evidence'][:500]}`")
            lines.append("")
        if f.get("fix"):
            lines.append(f"**Fix:** {f['fix']}")
            lines.append("")
        snippets = f.get("snippets") or {}
        for server, code in list(snippets.items())[:2]:
            lines.append(f"<details><summary>{server}</summary>\n\n```\n{code}\n```\n</details>\n")
    info = [f for f in findings if f["severity"] == "info"]
    if info:
        lines += ["## Notes", ""]
        lines += [f"- {ICON['info']} {_esc(f['title'])}" for f in info]
    if show_passed:
        passed = [f for f in findings if f["severity"] == "pass"]
        if passed:
            lines += ["", "## Passed checks", ""]
            lines += [f"- {ICON['pass']} {_esc(f['title'])}" for f in passed]
    comp = report.get("compliance", {})
    if comp:
        lines += ["", "## Compliance", "", "| Standard | Result | Problems |", "|---|---|---|"]
        for v in comp.values():
            lines.append(f"| {v['name']} | {'✅ pass' if v['compliant'] else '❌ fail'} | {_esc('; '.join(v['problems'][:3]))} |")
    lines += ["", "---", f"_Generated by Sitewarden {report.get('version', '')}. Passive checks only._", ""]
    return "\n".join(lines)
